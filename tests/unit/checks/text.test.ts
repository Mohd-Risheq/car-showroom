import { describe, expect, it } from "vitest";
import { cssComment, inWords } from "../../../scripts/checks/text.ts";

// The words the check scripts write: a list in a sentence, and a generated CSS file's comment.

describe("inWords", () => {
  it("writes a list as a sentence does, with and before its last item", () => {
    expect(inWords([])).toBe("");
    expect(inWords(["body"])).toBe("body");
    expect(inWords(["body", "small"])).toBe("body and small");
    expect(inWords([40, 60, 80])).toBe("40, 60 and 80");
  });
});

describe("cssComment", () => {
  it("opens a comment, sets each line under the first's text and closes it after the last", () => {
    expect(cssComment(["One line."])).toBe("/* One line. */");
    expect(cssComment(["Generated by a script:", "run it again."])).toBe(
      "/* Generated by a script:\n   run it again. */",
    );
  });
});
